import { expect, test } from '@playwright/test'
for (const theme of ['light', 'dark'] as const) for (const width of [1440, 393]) {
  test(`workspace navigation, inline table and keyboard selectors ${theme} ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.addInitScript((theme) => localStorage.setItem('kw-theme', theme), theme)
    await page.goto('/')
    await expect(page).toHaveURL(/projects\/website\/table$/)
    await page.goto('/projects?workspace=team')
    await page.getByLabel('New project name').fill('Reference workspace')
    await page.getByRole('button', { name: 'New project', exact: true }).click()
    await page.locator('main').getByRole('link', { name: /Reference workspace/ }).click()
    await page.getByRole('button', { name: 'Edit project', exact: true }).click()
    const editor = page.getByRole('dialog', { name: 'Edit project' })
    await editor.getByRole('combobox', { name: 'Workspace', exact: true }).click()
    await page.getByRole('option', { name: 'Personal Workspace', exact: true }).click()
    await editor.getByRole('button', { name: 'Save changes' }).click()
    await page.getByRole('button', { name: 'New task', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    const title = page.getByLabel('Title for New task', { exact: true })
    await title.fill('Inline task')
    await page.getByRole('combobox', { name: 'Status for Inline task' }).press('ArrowDown')
    await page.getByRole('listbox').press('End')
    await page.getByRole('option', { name: 'Done', exact: true }).press('Enter')
    await expect(page.getByRole('combobox', { name: 'Status for Inline task' })).toContainText('Done')
    await page.getByLabel('Description for Inline task').fill('Preserved description')
    const projectUrl = page.url()
    await page.goto('/')
    await expect(page).toHaveURL(projectUrl)
    await expect(page.getByLabel('Description for Inline task')).toHaveValue('Preserved description')
    await expect(page.getByRole('button', { name: /^Open Inline/ })).toHaveCount(0)
    await expect(page.getByText('Your personal workspace · Changes saved on this device')).toHaveCount(0)
    const headers = page.locator('.task-table thead th')
    await expect(headers).toHaveCount(5)
    expect((await headers.allTextContents()).map((v) => v.replace(/[↑↓]/g, '').trim())).toEqual(['AaTask name', 'Status', 'Priority', 'Due date', 'Description'])
    await expect(page.locator('.main')).toHaveCSS('background-color', theme === 'light' ? 'rgb(255, 255, 255)' : 'rgb(25, 25, 25)')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    if (width < 1024) await page.getByRole('button', { name: 'Open sidebar', exact: true }).click()
    const nav = page.getByRole('navigation', { name: 'Primary', exact: true })
    for (const name of ['Home', 'Calendar', 'My tasks', 'Favorites', 'Pages', 'New page']) await expect(nav.getByText(name, { exact: true })).toHaveCount(0)
    await expect(nav.getByText('Team Workspace', { exact: true })).toBeVisible()
    await expect(nav.getByText('Personal Workspace', { exact: true })).toBeVisible()
    const personal = nav.locator('.nav-section').filter({ hasText: 'Personal Workspace' })
    await expect(personal.getByRole('link', { name: /Reference workspace/ })).toHaveCount(1)
  })
}
