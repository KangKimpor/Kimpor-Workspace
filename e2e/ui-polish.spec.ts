import { expect, test } from './workspace-test'
import AxeBuilder from '@axe-core/playwright'

test('polished views, glass menus, project drafts and calendar layers', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1280, height: 890 })
  await page.addInitScript(() => localStorage.setItem('kw-theme', 'light'))
  await page.goto('/tasks')
  await page.getByRole('heading', { name: 'My tasks' }).waitFor()
  await page.getByRole('combobox', { name: 'Filter by priority' }).click()
  await page.getByRole('option', { name: 'High', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Filter by priority' })).toHaveText('High')
  await page.getByRole('combobox', { name: 'Filter by priority' }).click()
  await page.getByRole('option', { name: 'All priorities' }).click()
  await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/tasks-polished.png' })
  await page.getByRole('combobox', { name: 'Filter by project' }).click()
  await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/glass-selectors.png' })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Saved views', exact: true }).click()
  await page.getByLabel('Name for saved view').fill('Focused work')
  await page.getByRole('button', { name: 'Save view', exact: true }).click()
  await page.keyboard.press('Escape')
  await page.goto('/projects/website/overview')
  await expect(page).toHaveURL(/\/projects\/website\/table$/)
  await expect(page.getByRole('navigation', { name: 'Project views' }).getByRole('link')).toHaveCount(2)
  await page.getByRole('button', { name: 'Edit project', exact: true }).click()
  const editor = page.getByRole('dialog')
  await editor.getByLabel('Project name').fill('Discarded draft')
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Website Redesign' })).toBeVisible()
  await page.getByRole('button', { name: 'Edit project', exact: true }).click()
  await editor.getByRole('combobox', { name: 'Status', exact: true }).click()
  await page.getByRole('option', { name: 'On hold', exact: true }).click()
  await expect(editor.getByRole('combobox', { name: 'Status', exact: true })).toHaveText('On hold')
  await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/project-editor-polished.png' })
  await editor.getByRole('button', { name: 'Save changes', exact: true }).click()
  await page.getByRole('button', { name: 'Edit project', exact: true }).click()
  await expect(editor.getByRole('combobox', { name: 'Status', exact: true })).toHaveText('On hold')
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/project-table-polished.png' })
  await page.goto('/calendar/week/today')
  await page.getByRole('button', { name: /Calendars/ }).click()
  await page.getByRole('checkbox', { name: 'Work', exact: true }).uncheck()
  await expect(page.getByRole('checkbox', { name: 'Work', exact: true })).not.toBeChecked()
  await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/calendar-picker-polished.png' })
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/tasks')
  await page.getByRole('heading', { name: 'My tasks' }).waitFor()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/tasks-mobile-polished.png' })
  const accessibility = await new AxeBuilder({ page }).analyze()
  expect(accessibility.violations).toEqual([])
  expect(errors).toEqual([])
})
